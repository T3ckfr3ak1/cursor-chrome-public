'use strict';

/**
 * Keep agent docs in sync with the live API.
 * - Regenerates docs/API.generated.md from agent-api.js + client.js
 * - Copies project skill → ~/.cursor/skills/cursor-chrome/SKILL.md
 * - Reminds if THREAD-PROTOCOL is older than API sources (mtime hint)
 *
 * Run: npm run docs:sync
 */

const fs = require('fs');
const path = require('path');

const ROOT = path.join(__dirname, '..');
const AGENT_API = path.join(ROOT, 'src', 'agent-api.js');
const ROUTES_POWER = path.join(ROOT, 'src', 'routes-power.js');
const CLIENT = path.join(ROOT, 'src', 'client.js');
const PROTOCOL = path.join(ROOT, 'docs', 'THREAD-PROTOCOL.md');
const SKILL_SRC = path.join(ROOT, '.cursor', 'skills', 'cursor-chrome', 'SKILL.md');
const SKILL_DST = path.join(
  process.env.USERPROFILE || process.env.HOME || '',
  '.cursor',
  'skills',
  'cursor-chrome',
  'SKILL.md'
);
const OUT = path.join(ROOT, 'docs', 'API.generated.md');

function extractRoutes(src) {
  const routes = [];
  const re = /app\.(get|post|delete|put|patch)\(\s*(?:\[([^\]]+)\]|'([^']+)'|"([^"]+)")/g;
  let m;
  while ((m = re.exec(src))) {
    const method = m[1].toUpperCase();
    const multi = m[2];
    const single = m[3] || m[4];
    if (multi) {
      for (const part of multi.split(',')) {
        const p = part.trim().replace(/^['"]|['"]$/g, '');
        if (p) routes.push({ method, path: p });
      }
    } else if (single) {
      routes.push({ method, path: single });
    }
  }
  return routes;
}

function extractClientMethods(src) {
  const methods = [];
  const re = /^\s{2}(?:async\s+)?([a-zA-Z][a-zA-Z0-9]*)\s*\(/gm;
  let m;
  while ((m = re.exec(src))) {
    const name = m[1];
    if (name === 'constructor' || name.startsWith('_')) continue;
    methods.push(name);
  }
  return [...new Set(methods)];
}

function main() {
  const apiSrc = fs.readFileSync(AGENT_API, 'utf8');
  const powerSrc = fs.existsSync(ROUTES_POWER) ? fs.readFileSync(ROUTES_POWER, 'utf8') : '';
  const clientSrc = fs.readFileSync(CLIENT, 'utf8');
  const routes = [...extractRoutes(apiSrc), ...extractRoutes(powerSrc)];
  // de-dupe by method+path
  const seen = new Set();
  const unique = [];
  for (const r of routes) {
    const k = `${r.method} ${r.path}`;
    if (seen.has(k)) continue;
    seen.add(k);
    unique.push(r);
  }
  const methods = extractClientMethods(clientSrc);
  const now = new Date().toISOString();

  const lines = [
    `# Cursor-Chrome API (generated)`,
    ``,
    `> Auto-generated by \`npm run docs:sync\` at **${now}**. Do not edit by hand.`,
    `> Full thread instructions: [THREAD-PROTOCOL.md](./THREAD-PROTOCOL.md)`,
    ``,
    `## Client methods (\`src/client.js\`)`,
    ``,
    ...methods.map((m) => `- \`${m}\``),
    ``,
    `## REST routes (\`src/agent-api.js\` + \`src/routes-power.js\`)`,
    ``,
    `| Method | Path |`,
    `|--------|------|`,
    ...unique.map((r) => `| ${r.method} | \`${r.path}\` |`),
    ``,
    `## Ports`,
    ``,
    `- Agent API: \`http://127.0.0.1:9222\``,
    `- Live viewer: \`http://127.0.0.1:9222/live\``,
    `- CDP: \`http://127.0.0.1:9223\``,
    `- Stream WS: \`ws://127.0.0.1:9222/stream\``,
    `- Events WS: \`ws://127.0.0.1:9222/ws\``,
    `- MCP: \`node mcp/server.js\` (\`npm run mcp\`)`,
    ``,
  ];

  fs.mkdirSync(path.dirname(OUT), { recursive: true });
  fs.writeFileSync(OUT, lines.join('\n'), 'utf8');
  console.log(`Wrote ${path.relative(ROOT, OUT)} (${unique.length} routes, ${methods.length} client methods)`);

  // Sync skill to user skills dir
  if (!fs.existsSync(SKILL_SRC)) {
    console.warn('Missing project skill:', SKILL_SRC);
  } else {
    fs.mkdirSync(path.dirname(SKILL_DST), { recursive: true });
    fs.copyFileSync(SKILL_SRC, SKILL_DST);
    console.log(`Synced skill → ${SKILL_DST}`);
  }

  // Also copy protocol into skill folder for progressive disclosure
  const protocolDst = path.join(path.dirname(SKILL_DST), 'THREAD-PROTOCOL.md');
  if (fs.existsSync(PROTOCOL)) {
    fs.copyFileSync(PROTOCOL, protocolDst);
    fs.copyFileSync(PROTOCOL, path.join(ROOT, '.cursor', 'skills', 'cursor-chrome', 'THREAD-PROTOCOL.md'));
    console.log('Synced THREAD-PROTOCOL next to skill');
  }

  // mtime hint
  const apiTime = fs.statSync(AGENT_API).mtimeMs;
  const protoTime = fs.existsSync(PROTOCOL) ? fs.statSync(PROTOCOL).mtimeMs : 0;
  if (apiTime > protoTime + 1000) {
    console.warn(
      'NOTE: src/agent-api.js is newer than docs/THREAD-PROTOCOL.md — review playbooks if behavior changed.'
    );
  }

  console.log('docs:sync complete');
}

main();
